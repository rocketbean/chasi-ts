import fs from "fs";
import path from "path";
import type {
  SdkBuilderOutput,
  SdkBuilderTyped,
  SdkBuildContext,
  SdkRouteEntry,
} from "./SdkBuilder.types.js";
import type RouteCollector from "./collectors/Routes.js";

// ─── Namespace tree node ──────────────────────────────────────────────────────

/**
 * A node in the generated SDK's nested namespace tree. Leaves carry a `route`
 * (emitted as a function); inner nodes carry `children` (emitted as objects).
 */
type TreeNode = {
  children: Map<string, TreeNode>;
  route?: SdkRouteEntry;
};

// ─── Compiler ────────────────────────────────────────────────────────────────

export default class Compiler {
  private _tree: TreeNode | null = null;

  /** Built-in/global type names that never need inlining (self-containment check). */
  private static readonly GLOBAL_TYPES = new Set([
    "Array", "ReadonlyArray", "Record", "Promise", "Partial", "Required",
    "Readonly", "Pick", "Omit", "Exclude", "Extract", "NonNullable",
    "ReturnType", "Parameters", "InstanceType", "Map", "ReadonlyMap", "Set",
    "ReadonlySet", "WeakMap", "WeakSet", "Date", "RegExp", "Error", "Object",
    "String", "Number", "Boolean", "Symbol", "BigInt", "Function", "Uint8Array",
    "ArrayBuffer", "Blob", "File", "FormData", "Iterable", "AsyncIterable",
  ]);

  constructor(
    private readonly output: SdkBuilderOutput,
    private readonly collector: RouteCollector
  ) {}

  // ─── Public entry ──────────────────────────────────────────────────────────

  async compile(): Promise<void> {
    await this.runSdkValidation();
    const code = this.generateBundle();
    await this.write(code);
    // Typed sidecar: build mode only — the parser needs `typescript` + `src/**`,
    // so the .d.ts is never written on the server-boot runtime path.
    if (this.output.typed?.enabled && globalThis.__chasiBuild) {
      await this.writeDeclarations(await this.generateDeclarations());
    }
  }

  // ─── sdk() build-phase validation ─────────────────────────────────────────

  /**
   * Iterates every collected route that has .sdk() handlers registered and
   * calls endpoint.runSdk(context) — executing the handler chain with a
   * SdkBuildContext so developers can validate route configuration at build
   * time rather than at request time.
   *
   * Failures are logged as warnings; they do not block code generation.
   */
  private async runSdkValidation(): Promise<void> {
    for (const route of this.collector.routes) {
      if (!route.hasSdkHandlers) continue;

      const context: SdkBuildContext = { config: this.output, route };

      try {
        let index = 0;
        const next = async (): Promise<void> => {
          if (index >= route.sdkHandlers.length) return;
          await route.sdkHandlers[index++](context, next);
        };
        await next();
        Logger.log(
          `[SdkBuilder] sdk() ✓ ${route.method.toUpperCase()} ${route.path}`
        );
      } catch (err: any) {
        Logger.log(
          `[SdkBuilder] sdk() ✗ ${route.method.toUpperCase()} ${route.path} — ${err?.message ?? err}`
        );
      }
    }
  }

  // ─── Bundle generation ─────────────────────────────────────────────────────

  private generateBundle(): string {
    const { httpClient = "fetch", host } = this.output;
    const lines: string[] = [];

    lines.push(`// Generated by chasi-ts sdkBuilder — do not edit manually.`);
    lines.push(`// Host: ${host}`);
    lines.push(`// Client: ${httpClient}`);
    lines.push(``);

    if (httpClient === "axios") {
      lines.push(`import axios from "axios";`);
      lines.push(``);
    }

    lines.push(`const HOST = ${JSON.stringify(host)};`);
    lines.push(``);
    lines.push(this.generateRequestHelper(httpClient));
    lines.push(``);
    lines.push(this.generateValidateHelper());
    lines.push(``);

    const hasSdkHandlers = this.collector.routes.some((r) => r.hasSdkHandlers);
    if (hasSdkHandlers) {
      lines.push(this.generateRunSdkHelper());
      lines.push(``);
    }

    lines.push(...this.emitTree());

    return lines.join("\n");
  }

  // ─── Namespace tree ────────────────────────────────────────────────────────

  /**
   * Builds a nested namespace tree. Each route's key path is
   * `[routerNamespace?, ...namespace, functionName]` — every segment before the
   * function name is a nesting level, the function name is the leaf. Two routes
   * resolving to the same key path trigger a tie-break: keep the one with the
   * fewest path params, log the dropped variant.
   */
  private buildTree(): TreeNode {
    const root: TreeNode = { children: new Map() };

    for (const route of this.collector.routes) {
      const keyPath = [
        ...(route.routerNamespace ? [route.routerNamespace] : []),
        ...route.namespace,
        route.functionName,
      ].filter((k) => !!k && k.length > 0);

      // A leaf needs at least [namespace, fn]; bucket stragglers under "sdk".
      if (keyPath.length < 2) keyPath.unshift("sdk");

      let node = root;
      for (let i = 0; i < keyPath.length - 1; i++) {
        const key = keyPath[i];
        let child = node.children.get(key);
        if (!child) {
          child = { children: new Map() };
          node.children.set(key, child);
        }
        node = child;
      }

      const leafKey = keyPath[keyPath.length - 1];
      const existing = node.children.get(leafKey);

      if (existing?.route) {
        const keep =
          this.pathParamCount(route.path) <
          this.pathParamCount(existing.route.path)
            ? route
            : existing.route;
        const drop = keep === route ? existing.route : route;
        Logger.log(
          `[SdkBuilder] name collision "${keyPath.join(".")}" — kept ${keep.method.toUpperCase()} ${keep.path}, dropped ${drop.method.toUpperCase()} ${drop.path}`
        );
        existing.route = keep;
      } else if (existing) {
        Logger.log(
          `[SdkBuilder] "${keyPath.join(".")}" is a namespace — route ${route.method.toUpperCase()} ${route.path} skipped`
        );
      } else {
        node.children.set(leafKey, { children: new Map(), route });
      }
    }

    return root;
  }

  // ─── Nested emit ─────────────────────────────────────────────────────────────

  /** Build the namespace tree once and reuse it (bundle + declarations). */
  private tree(): TreeNode {
    if (!this._tree) this._tree = this.buildTree();
    return this._tree;
  }

  private emitTree(): string[] {
    const root = this.tree();
    const lines: string[] = [];
    const topKeys: string[] = [];

    for (const [name, node] of root.children) {
      topKeys.push(name);
      lines.push(`export const ${name} = {`);
      lines.push(...this.emitNodeBody(node, "  "));
      lines.push(`};`);
      lines.push(``);
    }

    lines.push(`export default { ${topKeys.join(", ")} };`);
    return lines;
  }

  private emitNodeBody(node: TreeNode, indent: string): string[] {
    const lines: string[] = [];

    for (const [key, child] of node.children) {
      if (child.route && child.children.size === 0) {
        // leaf → function (the tree key equals route.functionName)
        lines.push(...this.generateRouteFunction(child.route, indent));
      } else {
        if (child.route) {
          Logger.log(
            `[SdkBuilder] "${key}" is both a route and a namespace — emitting as namespace`
          );
        }
        lines.push(`${indent}${key}: {`);
        lines.push(...this.emitNodeBody(child, indent + "  "));
        lines.push(`${indent}},`);
      }
    }

    return lines;
  }

  private pathParamCount(path: string): number {
    return path.split("/").filter((s) => s.startsWith(":")).length;
  }

  // ─── Typed declarations (.d.ts sidecar) ──────────────────────────────────────

  /**
   * Generate the sibling `.d.ts`, mirroring the `.js` tree 1:1 so consumers get
   * typed request/response shapes. Reuses the same namespace tree as the bundle.
   */
  private async generateDeclarations(): Promise<string> {
    const typed = this.output.typed!;
    const typeModule = typed.typeModule ?? "Chasi/Http/v2";
    const emit = typed.emit ?? "inline";
    const heads = this.collectTypeHeads();
    const lines: string[] = [];

    lines.push(`// Generated by chasi-ts sdkBuilder — do not edit manually.`);
    lines.push(`// Type declarations for ${this.output.filename}`);
    lines.push(``);
    if (heads.size) {
      if (emit === "import") {
        // Reference the external barrel — the consumer must resolve `typeModule`.
        lines.push(
          `import type { ${[...heads].sort().join(", ")} } from ${JSON.stringify(typeModule)};`
        );
        lines.push(``);
      } else {
        // Inline the referenced types (+ transitive closure) so the `.d.ts` is
        // self-contained and portable — no external imports.
        const ns = await this.inlineNamespaces(heads, typeModule);
        if (ns.length) {
          lines.push(...ns);
          lines.push(``);
        }
      }
    }
    lines.push(
      `type ReqBody<T> = T extends { body: infer B } ? B : Record<string, any>;`
    );
    lines.push(``);

    const topKeys: string[] = [];
    for (const [name, node] of this.tree().children) {
      topKeys.push(name);
      lines.push(`export declare const ${name}: {`);
      lines.push(...this.emitDeclBody(node, "  "));
      lines.push(`};`);
      lines.push(``);
    }

    lines.push(
      `declare const _default: { ${topKeys.map((k) => `${k}: typeof ${k}`).join("; ")} };`
    );
    lines.push(`export default _default;`);
    return lines.join("\n");
  }

  private emitDeclBody(node: TreeNode, indent: string): string[] {
    const lines: string[] = [];
    for (const [key, child] of node.children) {
      if (child.route && child.children.size === 0) {
        lines.push(...this.generateTypedSignature(child.route, indent));
      } else {
        lines.push(`${indent}${key}: {`);
        lines.push(...this.emitDeclBody(child, indent + "  "));
        lines.push(`${indent}};`);
      }
    }
    return lines;
  }

  /** One method signature in the `.d.ts`, mirroring the `.js` arg gating exactly. */
  private generateTypedSignature(route: SdkRouteEntry, indent: string): string[] {
    const fallback = this.output.typed?.fallback ?? {};
    const needsBody =
      !["get", "delete", "head"].includes(route.method.toLowerCase());
    const req = route.reqType
      ? `ReqBody<${route.reqType}>`
      : fallback.request ?? "Record<string, any>";
    const res = route.resType ?? fallback.response ?? "any";

    const meta: string[] = [
      `${route.method.toUpperCase()} ${route.path}`,
      route.isProtected ? "protected" : "public",
    ];
    if (route.middlewares.length) meta.push(`mw: [${route.middlewares.join(", ")}]`);

    const fn = route.functionName;
    let sig: string;
    if (needsBody && route.isProtected)
      sig = `${fn}(payload: ${req}, token: string): Promise<${res}>;`;
    else if (needsBody) sig = `${fn}(payload?: ${req}): Promise<${res}>;`;
    else if (route.isProtected) sig = `${fn}(token: string): Promise<${res}>;`;
    else sig = `${fn}(): Promise<${res}>;`;

    return [`${indent}/** ${meta.join(" · ")} */`, `${indent}${sig}`];
  }

  /** Leading barrel identifiers referenced by req/res FQNs, for the import line. */
  private collectTypeHeads(): Set<string> {
    const heads = new Set<string>();
    const add = (t?: string): void => {
      const m = t?.match(/^([A-Za-z0-9_$]+)\./);
      if (m) heads.add(m[1]);
    };
    for (const route of this.collector.routes) {
      add(route.reqType);
      add(route.resType);
    }
    return heads;
  }

  /**
   * Inline the barrel types referenced by the SDK (and their transitive
   * closure) as module-local `export declare namespace` blocks, so the emitted
   * `.d.ts` carries every type it uses and needs no external module. Warns if a
   * copied type references something outside the barrel (a self-containment leak).
   */
  private async inlineNamespaces(heads: Set<string>, typeModule: string): Promise<string[]> {
    const typed = this.output.typed!;
    const typesRoot = path.resolve(process.cwd(), typed.typesRoot ?? "src/types/http/v2");
    const { default: Signatures } = await import("./collectors/Signatures.js");
    const source = Signatures.loadTypeSource(typesRoot, typeModule);

    // Transitive closure: pull in any segment referenced by an included one.
    const included: string[] = [];
    const seen = new Set<string>();
    const queue = [...heads];
    while (queue.length) {
      const seg = queue.shift()!;
      if (seen.has(seg)) continue;
      seen.add(seg);
      const body = source.get(seg);
      if (body == null) {
        Logger.log(`[SdkBuilder] typed(inline): no source for "${seg}" under "${typeModule}"`);
        continue;
      }
      included.push(seg);
      for (const other of source.keys()) {
        if (!seen.has(other) && new RegExp(`\\b${other}\\b`).test(body)) queue.push(other);
      }
    }

    const includedSet = new Set(included);
    const out: string[] = [];
    for (const seg of included.sort()) {
      const body = source.get(seg)!;
      // Self-containment check — a qualified ref to a non-inlined, non-global id.
      for (const m of body.matchAll(/\b([A-Z][A-Za-z0-9_]*)\s*\./g)) {
        const id = m[1];
        if (!includedSet.has(id) && !Compiler.GLOBAL_TYPES.has(id)) {
          Logger.log(
            `[SdkBuilder] typed(inline): "${seg}" references external "${id}" — the .d.ts may not be self-contained (fix the "${typeModule}" barrel, or set typed.emit:"import")`
          );
        }
      }
      out.push(`export declare namespace ${seg} {`, this.indentBlock(body, "  "), `}`);
    }
    return out;
  }

  private indentBlock(text: string, indent: string): string {
    return text
      .split("\n")
      .map((l) => (l.trim() ? indent + l : l))
      .join("\n");
  }

  private async writeDeclarations(dts: string): Promise<void> {
    const typed = this.output.typed!;
    const target =
      typed.declarationFile ?? this.output.filename.replace(/\.js$/, ".d.ts");

    let content = dts.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
    content = await this.formatDeclarations(content, typed);

    const outPath = path.resolve(process.cwd(), target);
    try {
      await fs.promises.mkdir(path.dirname(outPath), { recursive: true });
      await fs.promises.writeFile(outPath, content, "utf-8");
      Logger.log(`[SdkBuilder] types written → ${target}`);
    } catch (err) {
      Logger.log(`[SdkBuilder] failed to write declarations: ${err}`);
    }
  }

  /**
   * Format the `.d.ts`. Uses `typed.formatter` when supplied, otherwise prettier
   * (`parser: "typescript"`), imported defensively — terser (the runtime
   * `output.formatter`) cannot parse `declare`/type syntax, so it is never used.
   */
  private async formatDeclarations(
    content: string,
    typed: SdkBuilderTyped
  ): Promise<string> {
    if (typed.formatter) {
      try {
        return (await typed.formatter(content)) ?? content;
      } catch (err) {
        Logger.log(`[SdkBuilder] .d.ts formatter failed, writing raw: ${err}`);
        return content;
      }
    }
    try {
      const prettier = await import("prettier");
      return await prettier.format(content, { parser: "typescript" });
    } catch (err) {
      Logger.log(`[SdkBuilder] prettier unavailable for .d.ts, writing raw: ${err}`);
      return content;
    }
  }

  // ─── Route function ────────────────────────────────────────────────────────

  private generateRouteFunction(route: SdkRouteEntry, indent: string): string[] {
    const args: string[] = [];
    const needsBody =
      !["get", "delete", "head"].includes(route.method.toLowerCase());

    if (needsBody) args.push("payload = {}");
    if (route.isProtected) args.push("token");

    const required = JSON.stringify(route.requiredFields);
    const payloadArg = needsBody ? "payload" : "null";
    const tokenArg = route.isProtected ? ", token" : "";
    const sdkParam = needsBody ? "payload" : "null";

    const meta: string[] = [
      `${route.method.toUpperCase()} ${route.path}`,
      route.isProtected ? "protected" : "public",
    ];
    if (route.middlewares.length) meta.push(`mw: [${route.middlewares.join(", ")}]`);
    if (route.hasSdkHandlers) meta.push("sdk() validated");

    const lines: string[] = [
      `${indent}/** ${meta.join(" · ")} */`,
      `${indent}${route.functionName}: async (${args.join(", ")}) => {`,
    ];

    // required-field validation from spec
    if (needsBody) {
      lines.push(`${indent}  _validate(payload, ${required});`);
    }

    // inline sdk() handlers — serialised and executed before the request
    if (route.hasSdkHandlers) {
      const serialized = route.sdkHandlers
        .map((fn) => fn.toString())
        .join(`,\n${indent}    `);
      lines.push(`${indent}  await _runSdk(${sdkParam}, [`);
      lines.push(`${indent}    ${serialized}`);
      lines.push(`${indent}  ]);`);
    }

    lines.push(
      `${indent}  return _request("${route.method}", ${JSON.stringify(route.path)}, ${payloadArg}${tokenArg});`,
      `${indent}},`
    );

    return lines;
  }

  // ─── _runSdk helper ────────────────────────────────────────────────────────

  private generateRunSdkHelper(): string {
    return [
      `async function _runSdk(params, handlers) {`,
      `  let i = 0;`,
      `  const next = async () => {`,
      `    if (i >= handlers.length) return;`,
      `    await handlers[i++](params, next);`,
      `  };`,
      `  await next();`,
      `}`,
    ].join("\n");
  }

  // ─── _request helper ───────────────────────────────────────────────────────

  private generateRequestHelper(client: string): string {
    if (client === "axios") {
      return [
        `async function _request(method, path, payload, token) {`,
        `  const headers = { "Content-Type": "application/json" };`,
        `  if (token) headers["Authorization"] = \`Bearer \${token}\`;`,
        `  try {`,
        `    const res = await axios({ method, url: HOST + path, headers, data: payload });`,
        `    return res.data;`,
        `  } catch (err) {`,
        `    throw err?.response?.data ?? { message: err.message };`,
        `  }`,
        `}`,
      ].join("\n");
    }

    return [
      `async function _request(method, path, payload, token) {`,
      `  const headers = { "Content-Type": "application/json" };`,
      `  if (token) headers["Authorization"] = \`Bearer \${token}\`;`,
      `  const options = { method: method.toUpperCase(), headers };`,
      `  if (payload && method.toLowerCase() !== "get") options.body = JSON.stringify(payload);`,
      `  const res = await fetch(HOST + path, options);`,
      `  if (!res.ok) {`,
      `    const err = await res.json().catch(() => ({ message: res.statusText, status: res.status }));`,
      `    throw err;`,
      `  }`,
      `  return res.json().catch(() => null);`,
      `}`,
    ].join("\n");
  }

  // ─── _validate helper ─────────────────────────────────────────────────────

  private generateValidateHelper(): string {
    return [
      `function _validate(payload = {}, required = []) {`,
      `  for (const field of required) {`,
      `    const val = payload[field];`,
      `    if (val === undefined || val === null || val === "") {`,
      `      throw { status: 422, message: \`[SDK] Missing required field: "\${field}"\` };`,
      `    }`,
      `  }`,
      `}`,
    ].join("\n");
  }

  // ─── File writer ───────────────────────────────────────────────────────────

  private async write(code: string): Promise<void> {
    const { filename, formatter } = this.output;

    // Normalise whitespace in the raw output, then hand off to the formatter
    let content = code.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";

    if (formatter) {
      try {
        content = (await formatter(content)) ?? content;
      } catch (err) {
        Logger.log(`[SdkBuilder] formatter failed, writing unformatted output: ${err}`);
      }
    }

    // Always resolve relative to the project root (process.cwd())
    const outPath = path.resolve(process.cwd(), filename);
    const outDir  = path.dirname(outPath);

    try {
      await fs.promises.mkdir(outDir, { recursive: true });
      await fs.promises.writeFile(outPath, content, "utf-8");
      Logger.log(`[SdkBuilder] SDK written → ${filename}`);
    } catch (err) {
      Logger.log(`[SdkBuilder] failed to write SDK: ${err}`);
    }
  }

  // ─── Helpers ──────────────────────────────────────────────────────────────

  private toCamelCase(str: string): string {
    return str.replace(/[-_](.)/g, (_, c: string) => c.toUpperCase());
  }
}
